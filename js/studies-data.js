class StudiesManager {
  constructor() {
    this.storageKey = 'bp_emanuel_studies';
    this.init();
  }

  init() {
    if (!localStorage.getItem(this.storageKey)) {
      localStorage.setItem(this.storageKey, JSON.stringify(DEFAULT_STUDIES));
    }
  }

  getAllStudies() {
    try {
      const data = localStorage.getItem(this.storageKey);
      return data ? JSON.parse(data) : DEFAULT_STUDIES;
    } catch (e) {
      return DEFAULT_STUDIES;
    }
  }

  getStudyById(id) {
    const studies = this.getAllStudies();
    return studies.find(s => s.id === id);
  }

  addStudy(newStudy) {
    const studies = this.getAllStudies();
    newStudy.id = 'estudo-' + Date.now();
    newStudy.date = new Date().toLocaleDateString('pt-BR');
    studies.unshift(newStudy);
    localStorage.setItem(this.storageKey, JSON.stringify(studies));
    return newStudy;
  }
}

const studiesManager = new StudiesManager();
